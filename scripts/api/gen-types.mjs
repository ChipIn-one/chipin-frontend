// Generates `src/shared/api/generated/schema.d.ts` and `wireFields.ts` from openapi/chipin.yaml
// (spec 03 §4.3, §5). Exit 1 when a wire field check fails; nothing is written then.
//
// Usage: node scripts/api/gen-types.mjs [--spec <yaml>] [--out <dir>]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

import { openapiTsOptions } from './openapi-ts.config.mjs';
import { checkGeneratedTypes, checkWireFields, renderWireFields } from './wire-fields.mjs';

const repoRoot = resolve(import.meta.dirname, '../..');

const HEADER =
    '// Generated by scripts/api/gen-types.mjs from openapi/chipin.yaml (openapi-typescript). Do not edit.\n';

/** `{ schema, wireFields }` texts, or throws with every failed check. */
export const generate = async specPath => {
    const errors = checkWireFields(parse(readFileSync(specPath, 'utf8')));

    if (errors.length === 0) {
        const schema =
            HEADER + astToString(await openapiTS(pathToFileURL(specPath), openapiTsOptions));

        errors.push(...checkGeneratedTypes(schema));

        if (errors.length === 0) {
            return { schema, wireFields: renderWireFields() };
        }
    }
    throw new Error(`wire field checks failed:\n${errors.map(error => `  ${error}`).join('\n')}`);
};

const option = (argv, name, fallback) => {
    const index = argv.indexOf(name);

    return index === -1 ? fallback : resolve(argv[index + 1]);
};

export const main = async (argv = process.argv.slice(2)) => {
    const specPath = option(argv, '--spec', join(repoRoot, 'openapi/chipin.yaml'));
    const outDir = option(argv, '--out', join(repoRoot, 'src/shared/api/generated'));
    const { schema, wireFields } = await generate(specPath);

    mkdirSync(outDir, { recursive: true });
    writeFileSync(join(outDir, 'schema.d.ts'), schema);
    writeFileSync(join(outDir, 'wireFields.ts'), wireFields);
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main().catch(error => {
        process.stderr.write(`gen-types: ${error.message}\n`);
        process.exit(1);
    });
}
