// Writes MODEL_SHAPE_HASH (spec 03 §1.4) to src/shared/offline/modelHash.generated.ts: the first
// 12 hex of sha256 over src/entities/*/model/types.ts (paths sorted), each file re-printed by the
// TypeScript printer without comments, so comments and formatting do not change the hash.
//
// Usage: node scripts/offline/write-model-hash.mjs
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import ts from 'typescript';

const repoRoot = resolve(import.meta.dirname, '../..');

export const OUTPUT_PATH = 'src/shared/offline/modelHash.generated.ts';

const printer = ts.createPrinter({ removeComments: true });

const shape = (path, text) =>
    printer.printFile(
        ts.createSourceFile(path, text, ts.ScriptTarget.Latest, false, ts.ScriptKind.TS),
    );

/** @param {{ path: string, text: string }[]} files repository-relative POSIX paths */
export const modelShapeHash = files => {
    const hash = createHash('sha256');

    for (const { path, text } of [...files].sort((a, b) => (a.path < b.path ? -1 : 1))) {
        hash.update(`${path}\0${shape(path, text)}\0`);
    }
    return hash.digest('hex').slice(0, 12);
};

/** `src/entities/<entity>/model/types.ts` files of the repository. */
export const modelTypeFiles = (root = repoRoot) => {
    const entities = join(root, 'src/entities');

    if (!existsSync(entities)) {
        return [];
    }
    return readdirSync(entities, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => `src/entities/${entry.name}/model/types.ts`)
        .filter(path => existsSync(join(root, path)))
        .map(path => ({ path, text: readFileSync(join(root, path), 'utf8') }));
};

export const renderModelHash = hash =>
    '// Generated by scripts/offline/write-model-hash.mjs (npm run api:gen). Do not edit.\n' +
    '// The shape of the persisted domain model: part of the query cache buster (spec 03 §1.4).\n' +
    `export const MODEL_SHAPE_HASH = '${hash}';\n`;

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    mkdirSync(dirname(join(repoRoot, OUTPUT_PATH)), { recursive: true });
    writeFileSync(join(repoRoot, OUTPUT_PATH), renderModelHash(modelShapeHash(modelTypeFiles())));
}
